def names() -> Tuple[str, ...]:
    """Every drawable sprite name (templates excluded)."""
    return tuple(sorted(set(ART) - set(TEMPLATES) | set(REMAPS)))


FACINGS = ("down", "up", "left", "right")
# Walk cycle: stand, left foot up, stand, right foot up (frame ids into render())
WALK_CYCLE = (2, 0, 3, 0)
STEP_FRAMES = (2, 3)
