# Weapons are drawn procedurally from a short spec so one spec serves both the
# raised (vertical) and the striking (horizontal) blade. ``blade`` runs from the
# tip to the guard; ``edge`` is the highlight along one side.
WEAPONS: Dict[str, Dict[str, str]] = {
    "dagger": {"blade": "llgo", "edge": "w", "guard": "y"},
    "sword_bone": {"blade": "wwlwlw", "edge": "W", "guard": "Y"},
    "sword_dark": {"blade": "GdGGdG", "edge": "l", "guard": "g"},
    "sword_void": {"blade": "pPpPpd", "edge": "k", "guard": "P"},
}
# Weapon item id -> weapon art; other weapon items get a plain sword
WEAPON_ART = {
    "dagger_rust": "dagger", "blade_bone": "sword_bone",
    "blade_mourning": "sword_dark", "blade_oblivion": "sword_void",
}


def weapon_art(item_id: Optional[str]) -> Optional[str]:
    """The weapon art for an equipped weapon item (``None`` when unarmed)."""
    if not item_id:
        return None
    return WEAPON_ART.get(item_id, "sword_bone")


def weapon_pixels(kind: str, direction: str) -> Dict[Tuple[int, int], str]:
    """Palette letters of a weapon, keyed by offset from the hand, blade along
    ``direction`` ("up" or "left"). The grip is left to the hand itself."""
    spec = WEAPONS[kind]
    dx, dy = (0, -1) if direction == "up" else (-1, 0)
    nx, ny = (1, 0) if direction == "up" else (0, 1)  # across the blade
    px: Dict[Tuple[int, int], str] = {}
    for k in (-2, -1, 0, 1, 2):  # the guard, one pixel past the hand
        px[(dx + nx * k, dy + ny * k)] = spec["guard"] if abs(k) < 2 else "#"
    for i, colour in enumerate(reversed(spec["blade"]), start=2):
        bx, by = dx * i, dy * i
        px[(bx, by)] = colour
        px[(bx + nx, by + ny)] = spec["edge"]
        px[(bx - nx, by - ny)] = "#"
        px[(bx + 2 * nx, by + 2 * ny)] = "#"
    tip = len(spec["blade"]) + 2
    px[(dx * tip, dy * tip)] = "#"
    px[(dx * tip + nx, dy * tip + ny)] = "#"
    return px


def has_poses(name: str) -> bool:
    """Does this sprite have drawn battle poses (attack and cast templates)?"""
    base = template_of(name)
    return all(f"{base}_{pose}" in ART32 for pose in POSES.values())


def pose_shift(name: str, frame: int) -> int:
    """Source pixels the body sits right of its usual place in this frame's template."""
    if not has_poses(name):
        return 0
    return POSE_SHIFT.get(POSES.get(frame, ""), 0)


def lean(img: Image.Image, name: str, frame: int) -> Image.Image:
    """Battle poses for sprites without drawn ones: rear back for the wind-up,
    lunge the upper body forward (right) for the strike, rise to cast."""
    size = img.size[0]
    k = max(1, size // RENDER_PX)
    out = Image.new("RGBA", img.size, (0, 0, 0, 0))
    if frame == ATTACK_FRAMES[1]:
        split = LEG_ROWS[0] * size // RENDER_PX if name in WALKERS else size
        out.paste(img.crop((0, 0, size - 3 * k, split)), (3 * k, 0))
        if split < size:
            out.paste(img.crop((0, split, size, size)), (0, split))
    elif frame == ATTACK_FRAMES[0]:
        out.paste(img.crop((k, k, size, size)), (0, 0))
    else:
        out.paste(img.crop((0, k, size, size)), (0, 0))
    return out


def _facing_template(base: str, facing: str) -> str:
    """The template variant for a facing: ``_up``/``_side`` when drawn, else the base."""
    if facing == "up" and f"{base}_up" in ART32:
        return f"{base}_up"
    if facing in ("left", "right") and f"{base}_side" in ART32:
        return f"{base}_side"
    return base


def _template(base: str, facing: str, frame: int) -> str:
    """A drawn battle pose when the frame asks for one, else the facing's template."""
    pose = POSES.get(frame)
    if pose is not None and f"{base}_{pose}" in ART32:
        return f"{base}_{pose}"
    return _facing_template(base, facing)


def grid(name: str, native: bool = True, facing: str = "down", frame: int = 0) -> str:
    """The resolved character grid for ``name`` (palette swaps applied).

    With ``native`` the 32x32 table is preferred when it has the sprite or the
    template a remap is built on; otherwise the 16x16 grid is returned.
    ``facing`` picks a back or side view where the template has one (right is
    drawn from the side view by mirroring in :func:`image`); a battle-pose
    ``frame`` picks the drawn pose instead where the template has it.
    """
    if name in REMAPS:
        base, mapping = REMAPS[name]
        if native and base in ART32:
            tmpl = _template(base, facing, frame)
            body = "".join(mapping.get(ch, ch) for ch in hd_grid(tmpl))
            return _overlay(body, name, tmpl, facing)
        return "".join(mapping.get(ch, ch) for ch in ART[base])
    if native and name in ART32:
        return hd_grid(_template(name, facing, frame))
    return ART[name]


def _overlay(body: str, name: str, tmpl: str, facing: str) -> str:
    """Draw a companion's overlay (hood, veil, beard) over its remapped body."""
    if tmpl.endswith("_up"):
        view = "up"
    elif tmpl.endswith("_side") or any(tmpl.endswith("_" + p) for p in POSES.values()):
        view = "side"
    else:
        view = "down"
    overlay = hd_overlay(name, view)
    if overlay is None:
        return body
    rows = body.split("\n")
    k = len(rows) // RENDER_PX  # 2 for HD grids
    shift = 0
    for pose, dx in POSE_SHIFT.items():
        if tmpl.endswith("_" + pose):
            shift = dx * k
    orows = overlay.split("\n")
    out = []
    for row, orow in zip(rows, orows):
        if shift:
            orow = "." * shift + orow[: len(orow) - shift]
        out.append("".join(o if o != "." else b for b, o in zip(row, orow)))
    return "\n".join(out)


def has_facings(name: str) -> bool:
    """Does this sprite turn (has back and side views)?"""
    base = REMAPS[name][0] if name in REMAPS else name
    return f"{base}_up" in ART32 and f"{base}_side" in ART32


def template_of(name: str) -> str:
    return REMAPS[name][0] if name in REMAPS else name


def grid_size(name: str) -> int:
    """Edge length of the grid :func:`grid` returns for ``name``."""
    return len(grid(name).split("\n"))


def image(
    name: str, scale: int = 1, native: bool = True, facing: str = "down",
    frame: int = 0, weapon: Optional[str] = None,
) -> Image.Image:
    """Render ``name`` to an RGBA image, ``scale`` pixels per cell (nearest neighbour).

    ``facing="right"`` mirrors the side view so the sprite looks right. A battle
    pose ``frame`` with a ``weapon`` (see :data:`WEAPONS`) draws the blade in the
    sprite's hand.
    """
    rows = grid(name, native, facing, frame).split("\n")
    size = len(rows)
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            px[x, y] = PALETTE[ch]
    anchor = WEAPON_ANCHORS.get(POSES.get(frame, ""))
    if weapon is not None and anchor is not None and native and has_poses(name):
        (hx, hy), direction = anchor
        k = size // RENDER_PX  # weapon specs are in 32 px units
        for (ox, oy), ch in weapon_pixels(weapon, direction).items():
            for sy in range(k):
                for sx in range(k):
                    x, y = (hx + ox) * k + sx, (hy + oy) * k + sy
                    if 0 <= x < size and 0 <= y < size:
                        px[x, y] = PALETTE[ch]
    if facing == "right" and has_facings(name):
        img = img.transpose(Image.FLIP_LEFT_RIGHT)
    if scale != 1:
        img = img.resize((size * scale, size * scale), Image.NEAREST)
    return img


def step(img: Image.Image, name: str, which: int, facing: str = "down") -> Image.Image:
    """A walking pose: lift one leg two pixels (``which`` 0 = left half, 1 = right).

    Works on the native 32 px source: the leg rows are shifted up within their
    half of the sprite and the vacated pixels cleared, so the foot visibly
    rises and the stride reads at a glance.
    """
    size = img.size[0]
    if size % RENDER_PX or not (has_facings(name) or name in WALKERS):
        return img
    k = size // RENDER_PX
    tmpl = _facing_template(template_of(name), facing)
    split = LEG_SPLIT.get(tmpl, LEG_SPLIT_DEFAULT) * k
    if facing == "right" and has_facings(name):
        split = size - split
        which = 1 - which
    x0, x1 = (0, split) if which == 0 else (split, size)
    top, bottom = LEG_ROWS[0] * k, LEG_ROWS[1] * k
    lift = 2 * k
    out = img.copy()
    region = img.crop((x0, top + lift, x1, bottom))
    out.paste(Image.new("RGBA", (x1 - x0, bottom - top), (0, 0, 0, 0)), (x0, top))
    out.paste(region, (x0, top))
    return out


# --- Rendering pipeline: 16x16 source -> 32x32 shaded sprite -----------------

RENDER_PX = SIZE * 2
OUTLINE = PALETTE["#"]
LIGHT = (-1, -1)  # light comes from the top-left


def epx(img: Image.Image) -> Image.Image:
    """Scale2x/EPX: double the size while smoothing diagonal steps, no blur."""
    w, h = img.size
    src = img.load()
    out = Image.new("RGBA", (w * 2, h * 2), (0, 0, 0, 0))
    dst = out.load()
    clear = (0, 0, 0, 0)

    def at(x: int, y: int):
        return src[x, y] if 0 <= x < w and 0 <= y < h else clear

    for y in range(h):
        for x in range(w):
            p = src[x, y]
            a, b, c, d = at(x, y - 1), at(x + 1, y), at(x - 1, y), at(x, y + 1)
            p1 = p2 = p3 = p4 = p
            if c == a and c != d and a != b:
                p1 = a
            if a == b and a != c and b != d:
                p2 = b
            if d == c and d != b and c != a:
                p3 = c
            if b == d and b != a and d != c:
                p4 = d
            dst[2 * x, 2 * y] = p1
            dst[2 * x + 1, 2 * y] = p2
            dst[2 * x, 2 * y + 1] = p3
            dst[2 * x + 1, 2 * y + 1] = p4
    return out


def _adjust(c, dv: float, ds: float = 0.0):
    r, g, b, a = c
    h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
    v = max(0.0, min(1.0, v + dv))
    s = max(0.0, min(1.0, s + ds))
    r, g, b = colorsys.hsv_to_rgb(h, s, v)
    return (int(r * 255), int(g * 255), int(b * 255), a)


def shade(img: Image.Image) -> Image.Image:
    """Give flat fills volume: a highlight on edges facing the light, a shadow
    on edges facing away, and a dithered half-shadow one pixel further in."""
    w, h = img.size
    src = img.load()
    out = img.copy()
    dst = out.load()

    def solid(x: int, y: int) -> bool:
        if 0 <= x < w and 0 <= y < h:
            c = src[x, y]
            return c[3] == 255 and c != OUTLINE
        return False

    lx, ly = LIGHT
    rows = [y for y in range(h) if any(src[x, y][3] == 255 for x in range(w))]
    top, bottom = (rows[0], rows[-1]) if rows else (0, h - 1)
    span = max(1, bottom - top)
    for y in range(h):
        depth = (y - top) / span  # 0 at the sprite's crown, 1 at its feet
        for x in range(w):
            c = src[x, y]
            if c[3] != 255 or c == OUTLINE:
                continue
            lit = not solid(x + lx, y + ly)
            dark = not solid(x - lx, y - ly)
            dark2 = not solid(x - 2 * lx, y - 2 * ly) and (x + y) % 2 == 0
            if lit and not dark:
                dst[x, y] = _adjust(c, 0.18, -0.08)
            elif dark:
                dst[x, y] = _adjust(c, -0.22, 0.08)
            elif dark2:
                dst[x, y] = _adjust(c, -0.11, 0.04)
            else:  # volume: a little brighter at the crown, darker towards the feet
                dst[x, y] = _adjust(c, 0.05 - 0.14 * depth, 0.03 * depth)
    return out


def tint_outlines(img: Image.Image) -> Image.Image:
    """Selective outlining: inner lines and the lit (top/left) silhouette take a
    dark tint of the colour they border instead of flat black, which reads as
    softer, more painted pixel art; the shadow-side silhouette stays black."""
    w, h = img.size
    src = img.load()
    out = img.copy()
    dst = out.load()

    def fill_at(x: int, y: int):
        if 0 <= x < w and 0 <= y < h:
            c = src[x, y]
            if c[3] and c != OUTLINE:
                return c
        return None

    def clear_at(x: int, y: int) -> bool:
        return not (0 <= x < w and 0 <= y < h) or src[x, y][3] == 0

    for y in range(h):
        for x in range(w):
            if src[x, y] != OUTLINE:
                continue
            if clear_at(x + 1, y) or clear_at(x, y + 1):
                continue  # shadow-side silhouette: keep it black for grounding
            neighbour = (fill_at(x + 1, y) or fill_at(x, y + 1) or fill_at(x - 1, y)
                         or fill_at(x, y - 1))
            if neighbour is None:
                continue
            r, g, b, _ = neighbour
            hh, ss, vv = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
            vv = min(0.30, vv * 0.45)
            ss = min(1.0, ss + 0.15)
            rr, gg, bb = colorsys.hsv_to_rgb(hh, ss, vv)
            dst[x, y] = (int(rr * 255), int(gg * 255), int(bb * 255), 255)
    return out


NECK_ROW = 16  # rows above this are the head in the humanoid templates


def bob(img: Image.Image, name: str) -> Image.Image:
    """The idle frame: walkers lift their head a pixel while their feet stay
    planted; everything else (floaters, blobs) rises whole."""
    size = img.size[0]
    out = Image.new("RGBA", img.size, (0, 0, 0, 0))
    if size % RENDER_PX == 0 and (has_facings(name) or name in WALKERS):
        k = size // RENDER_PX
        out.paste(img.crop((0, 0, size, size)), (0, 0))
        out.paste(img.crop((0, k, size, NECK_ROW * k + k)), (0, 0))
        return out
    lift = size // SIZE
    out.paste(img.crop((0, lift, size, size)), (0, 0))
    return out


def render(
    name: str, frame: int = 0, facing: str = "down", weapon: Optional[str] = None
) -> Image.Image:
    """The finished 32x32 sprite.

    Frames: 0 standing, 1 idle bob (the body lifted one source pixel, which
    reads as breathing), 2 and 3 the two walking poses (left or right leg
    raised; sprites without native legs fall back to the standing pose),
    4 and 5 the attack (blade raised, then the strike) and 6 casting. Sprites
    without drawn poses rear back, lunge and rise instead (:func:`lean`).
    """
    src = image(name, facing=facing, frame=frame, weapon=weapon)
    size = src.size[0]
    if frame == 1:
        src = bob(src, name)
    elif frame in STEP_FRAMES:
        src = step(src, name, frame - STEP_FRAMES[0], facing)
    elif frame in POSES and not has_poses(name):
        src = lean(src, name, frame)
    out = epx(src) if size < RENDER_PX else src
    if name not in TILES:
        out = tint_outlines(shade(out))
    return out


_textures: Dict[Tuple[str, int, str, Optional[str]], arcade.Texture] = {}


def texture(
    name: str, frame: int = 0, facing: str = "down", weapon: Optional[str] = None
) -> arcade.Texture:
    """The cached 32x32 arcade texture for ``name`` (see :func:`render` for frames)."""
    if not has_facings(name):
        facing = "down"
    if frame not in POSES or not has_poses(name):
        weapon = None
    key = (name, frame, facing, weapon)
    tex = _textures.get(key)
    if tex is None:
        tex = arcade.Texture(
            render(name, frame, facing, weapon),
            hash=f"pixelart:{name}:{frame}:{facing}:{weapon}",
        )
        _textures[key] = tex
    return tex


DISSOLVE_STEPS = 8


def _hash(x: int, y: int, salt: int = 0) -> float:
    """Stable per-pixel noise in [0, 1) (no random: deaths look the same every run)."""
    h = (x * 374761393 + y * 668265263 + salt * 1442695041) & 0xFFFFFFFF
    h = ((h ^ (h >> 13)) * 1274126177) & 0xFFFFFFFF
    return ((h ^ (h >> 16)) % 10007) / 10007.0


def dissolve(img: Image.Image, progress: float) -> Image.Image:
    """The sprite crumbling to ash: pixels vanish from the top down with a noisy
    edge, and what remains drains to grey. ``progress`` runs 0 (whole) to 1
    (gone)."""
    size = img.size[0]
    out = Image.new("RGBA", img.size, (0, 0, 0, 0))
    src = img.load()
    dst = out.load()
    for y in range(size):
        yn = y / max(1, size - 1)  # 0 at the top
        for x in range(size):
            r, g, b, a = src[x, y]
            if a == 0:
                continue
            survives = yn * 0.55 + _hash(x, y) * 0.45
            if progress > survives:
                continue
            grey = (r * 30 + g * 59 + b * 11) // 100
            k = min(1.0, progress * 1.4)
            dst[x, y] = (
                int(r + (grey + 20 - r) * k), int(g + (grey + 10 - g) * k),
                int(b + (grey - b) * k), a,
            )
    return out


_dissolve_cache: Dict[str, List[arcade.Texture]] = {}


def dissolve_frames(name: str, steps: int = DISSOLVE_STEPS) -> List[arcade.Texture]:
    """Cached textures of ``name`` crumbling away, from nearly whole to a last few motes."""
    frames_ = _dissolve_cache.get(name)
    if frames_ is None:
        base = render(name)
        frames_ = [
            arcade.Texture(dissolve(base, (i + 1) / (steps + 1)),
                           hash=f"pixelart:{name}:dissolve:{i}")
            for i in range(steps)
        ]
        _dissolve_cache[name] = frames_
    return frames_


def frames(name: str, facing: str = "down") -> List[arcade.Texture]:
    """Both idle frames for ``name``."""
    return [texture(name, 0, facing), texture(name, 1, facing)]


def walk_frame(t: float, period: float = 0.4) -> int:
    """Which render frame a walker shows ``t`` seconds into its stride cycle."""
    return WALK_CYCLE[int(t / period * len(WALK_CYCLE) + 1e-6) % len(WALK_CYCLE)]


def facing_from(dx: int, dy: int, current: str = "down") -> str:
    """The facing for a step of (dx, dy) on the map (dy > 0 is up on screen)."""
    if dx > 0:
        return "right"
    if dx < 0:
        return "left"
    if dy > 0:
        return "up"
    if dy < 0:
        return "down"
    return current


def sprite(name: str, center: Tuple[float, float], scale: float = 1.0) -> arcade.Sprite:
    """A sprite showing ``name`` centred at ``center`` (32 world px at scale 1,
    whatever the texture's own resolution)."""
    tex = texture(name)
    return arcade.Sprite(tex, scale=scale * RENDER_PX / tex.width,
                         center_x=center[0], center_y=center[1])


def enemy_sprite_name(def_id: str) -> str:
    """The sprite for an enemy definition id (unknown ids fall back to the skeleton)."""
    return def_id if def_id in ART or def_id in REMAPS else "skel_basic"


def party_sprite_name(companion_id: Optional[str]) -> str:
    """The sprite for a party member: the leader is the hero, companions their own art."""
    if companion_id and companion_id in REMAPS:
        return companion_id
    return "hero"


def item_icon(item) -> str:
    """The icon sprite for an item definition (anything with ``type``, ``id`` and
    ``mp_restore``): flasks by what they restore, gear by its slot."""
    kind = getattr(item, "type", "")
    item_id = getattr(item, "id", "")
    if kind == "potion":
        return "icon_tonic" if getattr(item, "mp_restore", 0) else "icon_potion"
    if kind == "consumable":
        return "icon_antidote"
    if kind == "scroll":
        return "icon_scroll"
    if kind == "weapon":
        return "icon_dagger" if item_id.startswith("dagger") else "icon_sword"
    if kind == "accessory":
        return "icon_boots" if "boots" in item_id else "icon_ring"
    if kind == "key":
        return "key"
    if kind == "token":
        return "icon_token"
    return {"armor": "icon_armor", "helm": "icon_helm", "shield": "icon_shield"}.get(
        kind, "icon_potion"
    )


def floor_variant(x: int, y: int) -> str:
    """Pick a flagstone variant from the tile position so floors are not uniform."""
    return FLOOR_VARIANTS[(x * 7 + y * 13) % len(FLOOR_VARIANTS)]


