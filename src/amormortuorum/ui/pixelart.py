"""Hand-drawn pixel art, authored as 16x16 character grids and rendered at runtime.

Every sprite is sixteen rows of sixteen characters. Each character picks a
colour from :data:`PALETTE` (``.`` is transparent). The grids live here as
plain text so the art is diffable, licence-free and ships inside the wheel
and the frozen build without any binary assets. Characters that share a body
plan are palette swaps of a template (see :data:`REMAPS`).

:func:`texture` renders a grid to an :class:`arcade.Texture` once and caches
it; :func:`image` returns the PIL image for tests and tooling.
"""
